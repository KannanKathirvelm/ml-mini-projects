#!/usr/bin/env python3
"""Generate per-flavor Android launcher icons, adaptive icon layers, splash colour and strings.

Reads src/flavors.json and writes android/app/src/<flavor>/res/... (Gradle flavor source sets
override main/res). Also writes resources/<flavor>/icon-1024.png as a reference image.
Icons are a white letter on the flavor colour: no third-party logos.
Requires Pillow (pip install pillow).
"""
import json
import os
from xml.sax.saxutils import escape

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FLAVORS = json.load(open(os.path.join(ROOT, "src", "flavors.json")))
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
FONT_CANDIDATES = [
    "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "C:/Windows/Fonts/arialbd.ttf",
]


def font(size):
    for f in FONT_CANDIDATES:
        if os.path.exists(f):
            return ImageFont.truetype(f, size)
    return ImageFont.load_default(size=size)


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def darker(rgb, k=0.72):
    return tuple(int(c * k) for c in rgb)


def draw_letter(img, letter, box_frac, color=(255, 255, 255, 255)):
    W, H = img.size
    d = ImageDraw.Draw(img)
    f = font(int(H * box_frac))
    l, t, r, b = d.textbbox((0, 0), letter, font=f)
    d.text(((W - (r - l)) / 2 - l, (H - (b - t)) / 2 - t), letter, font=f, fill=color)


def legacy_icon(size, rgb, letter, round_=False):
    S = size * 4  # supersample
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_:
        d.ellipse((0, 0, S - 1, S - 1), fill=rgb + (255,))
    else:
        d.rounded_rectangle((0, 0, S - 1, S - 1), radius=int(S * 0.22), fill=rgb + (255,))
    # subtle diagonal band for depth
    band = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(band).polygon([(0, S), (S, S * 0.45), (S, S)], fill=darker(rgb) + (110,))
    mask = Image.new("L", (S, S), 0)
    md = ImageDraw.Draw(mask)
    (md.ellipse if round_ else (lambda b, **k: md.rounded_rectangle(b, radius=int(S * 0.22), **k)))((0, 0, S - 1, S - 1), fill=255)
    band.putalpha(Image.composite(band.getchannel("A"), Image.new("L", (S, S), 0), mask))
    img = Image.alpha_composite(img, band)
    draw_letter(img, letter, 0.56)
    return img.resize((size, size), Image.LANCZOS)


def adaptive_foreground(size, letter):
    # 108dp canvas; keep glyph inside the 66dp safe zone.
    S = size * 4
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    draw_letter(img, letter, 0.40)
    return img.resize((size, size), Image.LANCZOS)


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(data)


def main():
    for fid, m in FLAVORS.items():
        rgb = hex_rgb(m["color"])
        res = os.path.join(ROOT, "android", "app", "src", fid, "res")
        for dname, k in DENSITIES.items():
            mip = os.path.join(res, f"mipmap-{dname}")
            os.makedirs(mip, exist_ok=True)
            legacy_icon(int(48 * k), rgb, m["letter"]).save(os.path.join(mip, "ic_launcher.png"))
            legacy_icon(int(48 * k), rgb, m["letter"], round_=True).save(os.path.join(mip, "ic_launcher_round.png"))
            adaptive_foreground(int(108 * k), m["letter"]).save(os.path.join(mip, "ic_launcher_foreground.png"))
        name = escape(m["appName"])
        write(os.path.join(res, "values", "flavor.xml"), f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-icons.py from src/flavors.json. Do not edit. -->
<resources>
    <string name="app_name">{name}</string>
    <string name="title_activity_main">{name}</string>
    <string name="package_name">com.kannan.mlapps.{fid}</string>
    <string name="custom_url_scheme">com.kannan.mlapps.{fid}</string>
    <color name="ic_launcher_background">{m["color"]}</color>
    <color name="splash_background">{m["color"]}</color>
    <color name="colorPrimary">{m["color"]}</color>
    <color name="colorPrimaryDark">#{''.join(f'{c:02x}' for c in darker(rgb))}</color>
    <color name="colorAccent">{m["color"]}</color>
</resources>
""")
        ref = os.path.join(ROOT, "resources", fid)
        os.makedirs(ref, exist_ok=True)
        legacy_icon(1024, rgb, m["letter"]).save(os.path.join(ref, "icon-1024.png"))
        print(f"{fid:11s} {m['appName']:24s} {m['color']}  -> {os.path.relpath(res, ROOT)}")


if __name__ == "__main__":
    main()
