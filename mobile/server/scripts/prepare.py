"""Copy just the files the API needs from projects 01-07 into server/projects/.

    python scripts/prepare.py            # source = the folder that contains mobile/
    SOURCE_ROOT=/path/to/repo python scripts/prepare.py

Safe to re-run: files are overwritten in place, nothing in projects/ is deleted,
so models trained into the copy (stocks, retrained sklearn models) survive.
The original project folders are only ever read.
"""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

SERVER = Path(__file__).resolve().parents[1]
SOURCE = Path(os.environ.get("SOURCE_ROOT", SERVER.parents[1])).resolve()
DEST = SERVER / "projects"

# project folder -> glob patterns (relative to that folder) to copy.
# Excluded on purpose: .venv, __pycache__, Streamlit app.py, outputs/, runs/, price CSV caches,
# datasets/, docs/, videos, the big synthetic CSVs and the 01/02 joblib pickles
# (those and their metrics.json are regenerated by scripts/build_models.py,
# so the pickles always match the installed scikit-learn).
MANIFEST: dict[str, list[str]] = {
    "01_credit_card_fraud_detection": [
        "generate_data.py", "train.py", "predict.py", "README.md",
    ],
    "02_upi_fraud_detection": [
        "generate_data.py", "train.py", "predict.py", "features.py", "README.md",
    ],
    "03_stock_price_prediction_lstm_rnn": [
        "data.py", "model.py", "predict.py", "train.py", "README.md",
        "india.py", "universal.py", "onnx_model.py", "train_universal.py", "export_onnx.py",
        "india_universe.txt", "data/nse_equities.csv", "data/nse_equities_meta.json",
        "models/*_rnn.pt", "models/*_lstm.pt", "models/*_rnn.onnx", "models/*_lstm.onnx",
        "models/*_meta.json",
    ],
    "04_financial_ai_agents": [
        "agents.py", "data_tools.py", "indicators.py", "llm.py", "pipeline.py", "report.py",
        "india.py", "data/nse_equities.csv", "data/nse_equities_meta.json", "README.md",
    ],
    "05_price_comparison_app": [
        "alerts.py", "config.py", "db.py", "formatting.py", "history.py", "matching.py",
        "search.py", "README.md", "stores/*.py", "data/catalog.json",
    ],
    "06_face_detection": [
        "detectors.py", "draw.py", "README.md", "models/*.onnx", "samples/*.jpg",
        "samples/*.png",
    ],
    "07_object_detection": [
        "config.py", "detector.py", "README.md", "weights/*.pt", "samples/*.jpg",
    ],
}
SKIP_PARTS = {".venv", "__pycache__", "outputs", "runs", "datasets", ".ultralytics"}


def main() -> int:
    missing = [p for p in MANIFEST if not (SOURCE / p).is_dir()]
    if missing:
        print(f"Source root {SOURCE} is missing: {missing}", file=sys.stderr)
        return 1
    total = 0
    for project, patterns in MANIFEST.items():
        src_root, dst_root = SOURCE / project, DEST / project
        n = 0
        for pattern in patterns:
            for src in sorted(src_root.glob(pattern)):
                rel = src.relative_to(src_root)
                if not src.is_file() or SKIP_PARTS & set(rel.parts):
                    continue
                dst = dst_root / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
                n += 1
        total += n
        print(f"  {project}: {n} files")
    print(f"Copied {total} files from {SOURCE} into {DEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
